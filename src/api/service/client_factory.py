"""Provider-independent chat client interface and factory."""  # Decouples the controller from any single AI provider by routing to the right client adapter.

from dataclasses import dataclass  # Create a simple response object shared by all provider implementations.
from typing import Protocol  # Define the common interface each provider client must implement.

from src.constants.app_constants import AppConstants  # Shared system instruction used for all provider requests.
from src.enums.error_codes import ErrorCode  # Error code returned when the provider is invalid.
from src.exceptions.custom_exception import AppException  # Base app exception type used to signal configuration and provider issues.
from src.enums.provider_enum import Provider  # Enumerated values for supported providers.


class ProviderRequestError(AppException):
    """A request to an external model provider failed."""  # Custom exception for upstream AI provider errors.

    def __init__(
        self,
        message: str,
        code: ErrorCode = ErrorCode.PROVIDER_REQUEST_FAILED,
    ) -> None:
        super().__init__(code, message)  # Store the provider error in the custom app exception base class.


@dataclass(frozen=True)
class ClientResponse:
    interaction_id: str  # Provider-specific identifier for follow-up context.
    text: str  # Text generated by the model for the caller.


class ChatClient(Protocol):
    def respond(
        self,
        prompt: str,
        previous_interaction_id: str | None = None,
        system_instruction: str = AppConstants.SAFETY_SYSTEM_INSTRUCTION,
    ) -> ClientResponse: ...  # Every provider client must accept the same call signature.


def create_client(provider: str | Provider) -> ChatClient:
    provider_value = provider.value if isinstance(provider, Provider) else provider  # Normalize enum or string provider values.
    if provider_value == Provider.OPENAI.value:
        from src.api.service.openai_client import OpenAIChatClient  # Import the OpenAI adapter only when needed.

        return OpenAIChatClient()  # Return the concrete OpenAI client implementation.
    if provider_value == Provider.GEMINI.value:
        from src.api.service.gemini_client import GeminiAIClient  # Import the Gemini adapter only when needed.

        return GeminiAIClient()  # Return the concrete Gemini client implementation.
    raise AppException(ErrorCode.INVALID_PROVIDER)  # Reject any unsupported provider identifier.


